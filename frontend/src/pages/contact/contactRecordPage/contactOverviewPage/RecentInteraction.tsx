import { Sparkles } from "lucide-react";
import { MdEmail } from "react-icons/md";
import { PiNotePencilLight } from "react-icons/pi";
import { useQuery } from "@tanstack/react-query";
import DataAnalysis from "../../../../assets/DataAnalysis.svg";
import { ThumbsUp, ThumbsDown } from "lucide-react";
import { Tooltip,TooltipTrigger, TooltipContent } from "../../../../ui/tooltip";

// ---------- Types ----------
type Note = {
  id: number;
  content: string;
  created_at: string;
};

type RecentInteractionData = {
  ownerName: string;
  notes: Note[];
};
// ---------- Fetch function (outside the component) ----------
const fetchRecentInteraction = async (
  contactId: number,
): Promise<RecentInteractionData> => {
  const base = import.meta.env.VITE_API_URL;

  const [contactRes, notesRes] = await Promise.all([
    fetch(`${base}/contacts/${contactId}`),
    fetch(`${base}/contacts/${contactId}/notes`),
  ]);

  // TanStack only knows about errors if you THROW
  if (!contactRes.ok) throw new Error(`Contact HTTP ${contactRes.status}`);
  if (!notesRes.ok) throw new Error(`Notes HTTP ${notesRes.status}`);

  const contact = await contactRes.json();
  const notes: Note[] = await notesRes.json();

  // newest note first
  const sorted = [...notes].sort(
    (a, b) =>
      new Date(b.created_at).getTime() - new Date(a.created_at).getTime(),
  );

  return {
    ownerName: contact.contactOwner ?? "",
    notes: sorted,
  };
};
const formatDate = (iso: string) =>
  new Date(iso).toLocaleDateString("en-IN", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });

// ---------- Component ----------
type Props = {
  contactId: number;
};
export default function RecentInteraction({ contactId }: Props) {
  const { data, isLoading, error } = useQuery({
    queryKey: ["recent-interaction", contactId],
    queryFn: () => fetchRecentInteraction(contactId),
    enabled: !!contactId, // don't fetch until we have an id
  });

  const latestNote = data?.notes[0];

  return (
    <div className="bg-white flex flex-col drop-shadow-xs rounded-2xl">
      <div className="flex flex-row items-center justify-between h-full w-full py-3 px-5">
        <span className="font-bold">Recent Interactions</span>
        <span className="inline-flex items-center gap-1 rounded-md bg-linear-to-r from-pink-600 to-orange-500 px-2 py-0.5   text-xs  font-semibold text-white">
          <Sparkles size={12} />
          AI
        </span>
      </div>

      <div className="m-3 rounded-xl flex flex-col">
        <span className="p-4">Generated by</span>
        <button className="w-fit flex flex-row items-center gap-2 border px-2 py-2 rounded-2xl cursor-pointer hover:bg-[#E0FCFA]">
          <MdEmail />
          <span>Create an email</span>
        </button>

        <div className="flex flex-col border rounded-xl p-5 mt-5">
          <p className="font-bold">Inbound</p>
          <div className="flex flex-col items-center p-4 gap-3">
            <img src={DataAnalysis} className="w-30 h-30" alt="No activity" />
            <span className="w-fit">No inbound Activity on this record</span>
          </div>
        </div>
      </div>

      <div className="flex py-3 px-5 ml-3 border flex-col rounded-2xl">
        <p className="font-bold mb-3">Outbound</p>

        {isLoading && <span>Loading...</span>}

        {error && (
          <span className="text-red-500">Failed to load: {error.message}</span>
        )}

        {data && !latestNote && <span>No notes yet</span>}

        {latestNote && (
          <div className="flex items-center gap-3">
            <PiNotePencilLight />
            <button className="hover:underline">Note</button>
            <span>
              by {data.ownerName || "Unknown"} ·{" "}
              {formatDate(latestNote.created_at)}
            </span>
          </div>
        )}
      </div>
     
      <div className="flex  m-3 ">
        <Tooltip>
          <TooltipTrigger asChild>

        <span className="p-2  hover:bg-gray-300 rounded">
          <ThumbsUp size={15} />
        </span>
          </TooltipTrigger>
          <TooltipContent side="bottom">
            <p>This is What I expected </p>
          </TooltipContent>
        </Tooltip>
     <Tooltip>
      <TooltipTrigger asChild>
        <span className="p-2 rounded hover:bg-gray-300">
          <ThumbsDown size={15} />
        </span>
      </TooltipTrigger>
      <TooltipContent side="bottom">
        <p>This is not what I expected</p>
      </TooltipContent>
     </Tooltip>
      </div>

    </div>
  );
}
